const plPlural = (n: number, one: string, few: string, many: string) => {
  const a = Math.abs(n);
  if (a === 1) return one;
  const d = a % 10, h = a % 100;
  return d >= 2 && d <= 4 && !(h >= 12 && h <= 14) ? few : many;
};

