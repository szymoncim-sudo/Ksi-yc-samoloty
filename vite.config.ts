import { CORS_HEADERS, handleFlights } from './shared/flight-proxy.mjs';

/** /api/flights during `vite dev` and `vite preview` (same contract as the Worker and Electron). */
function flightsApi(): Plugin {
  const mw = async (req: import('node:http').IncomingMessage, res: import('node:http').ServerResponse, next: () => void) => {
    if (!req.url || !req.url.startsWith('/api/flights')) return next();
    const url = new URL(req.url, 'http://localhost');
    const { status, body } = await handleFlights(url.searchParams);
    res.statusCode = status;
    for (const [k, v] of Object.entries(CORS_HEADERS)) res.setHeader(k, v);
    res.end(body);
  };
  return {
    name: 'lunaris-flights-api',
    configureServer(s) {
      s.middlewares.use(mw);
    },
    configurePreviewServer(s) {
      s.middlewares.use(mw);
    },
  };
}

/** iOS launch images (generated by scripts/make-assets.mjs). */
function iosSplash(): Plugin {
  return {
    name: 'lunaris-ios-splash',
    transformIndexHtml() {
      const list: { w: number; h: number; d: number; file: string }[] = JSON.parse(fs.readFileSync('scripts/splash-list.json', 'utf8'));
      return list.map((s) => ({
        tag: 'link',
        attrs: {
          rel: 'apple-touch-startup-image',
          href: `splash/${s.file}`,
          media: `(device-width: ${s.w}px) and (device-height: ${s.h}px) and (-webkit-device-pixel-ratio: ${s.d}) and (orientation: portrait)`,
        },
        injectTo: 'head' as const,
      }));
    },
  };
}

