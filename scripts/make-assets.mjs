// Generates all binary assets used by the app:
//  - Moon color textures (NASA LRO LROC WAC mosaic, public domain)
//  - Moon normal map derived from the LOLA 16 px/deg elevation model (public domain)
//  - Coarse EGM96 geoid grid (for MSL <-> WGS84 ellipsoid conversion)
//  - App icons, favicons, iOS splash screens, Electron icon (CPU-rendered real Moon)
//
// Source files (downloaded from NASA SVS "CGI Moon Kit", https://svs.gsfc.nasa.gov/4720):
//   assets-src/nasa-moon/lroc_color_poles_4k.tif
//   assets-src/nasa-moon/ldem_16_uint.tif
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { meanSeaLevel } from 'egm96-universal';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const SRC = path.join(ROOT, 'assets-src', 'nasa-moon');
const PUB = path.join(ROOT, 'public');
const out = (...p) => {
  const f = path.join(PUB, ...p);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  return f;
};
sharp.cache(false);
const big = { limitInputPixels: false };

const R_MOON = 1737400;

async function colorTextures() {
  const src = path.join(SRC, 'lroc_color_poles_4k.tif');
  await sharp(src, big).jpeg({ quality: 84, mozjpeg: true }).toFile(out('textures', 'moon-color-4k.jpg'));
  await sharp(src, big)
    .resize(2048, 1024, { kernel: 'lanczos3' })
    .jpeg({ quality: 86, mozjpeg: true })
    .toFile(out('textures', 'moon-color-2k.jpg'));
  console.log('color textures ok');
}

// Returns Float32Array heights (meters, relative) at the given size.
async function loadDem(w, h) {
  const { data, info } = await sharp(path.join(SRC, 'ldem_16_uint.tif'), big)
    .resize(w, h, { kernel: 'lanczos3' })
    .toColourspace('grey16')
    .raw({ depth: 'ushort' })
    .toBuffer({ resolveWithObject: true });
  const u16 = new Uint16Array(data.buffer, data.byteOffset, info.width * info.height * info.channels);
  const f = new Float32Array(w * h);
  for (let i = 0; i < w * h; i++) f[i] = u16[i * info.channels] * 0.5; // 0.5 m units
  return f;
}

function normalMapFromDem(dem, w, h, exaggeration) {
  const rgb = Buffer.alloc(w * h * 3);
  const dLon = (2 * Math.PI) / w;
  const dLat = Math.PI / h;
  for (let j = 0; j < h; j++) {
    const lat = Math.PI / 2 - (j + 0.5) * dLat;
    const cosLat = Math.max(Math.cos(lat), 0.02);
    const jn = Math.max(j - 1, 0);
    const js = Math.min(j + 1, h - 1);
    for (let i = 0; i < w; i++) {
      const ie = (i + 1) % w;
      const iw = (i - 1 + w) % w;
      const dhdx = (dem[j * w + ie] - dem[j * w + iw]) / (2 * dLon * R_MOON * cosLat);
      const dhdy = (dem[jn * w + i] - dem[js * w + i]) / ((js - jn) * dLat * R_MOON);
      let nx = -dhdx * exaggeration;
      let ny = -dhdy * exaggeration;
      let nz = 1;
      const l = Math.hypot(nx, ny, nz);
      nx /= l; ny /= l; nz /= l;
      const o = (j * w + i) * 3;
      rgb[o] = Math.round((nx * 0.5 + 0.5) * 255);
      rgb[o + 1] = Math.round((ny * 0.5 + 0.5) * 255);
      rgb[o + 2] = Math.round((nz * 0.5 + 0.5) * 255);
    }
  }
  return rgb;
}

async function normalMaps() {
  for (const [w, h, name] of [[2048, 1024, 'moon-normal-2k.jpg']]) {
    const dem = await loadDem(w, h);
    const rgb = normalMapFromDem(dem, w, h, 2.2);
    await sharp(rgb, { raw: { width: w, height: h, channels: 3 } })
      .jpeg({ quality: 88, mozjpeg: true, chromaSubsampling: '4:4:4' })
      .toFile(out('textures', name));
  }
  console.log('normal maps ok');
}

async function geoidGrid() {
  // 2-degree grid, lat 90..-90 (91 rows), lon -180..178 (180 cols), int16 decimeters
  const rows = 91, cols = 180;
  const arr = new Int16Array(rows * cols);
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      arr[r * cols + c] = Math.round(meanSeaLevel(90 - r * 2, -180 + c * 2) * 10);
    }
  }
  const b64 = Buffer.from(arr.buffer).toString('base64');
  const ts = `// Generated by scripts/make-assets.mjs from EGM96 (egm96-universal). Do not edit.\n` +
    `// 2° grid of geoid undulation N (meters*10), rows lat 90..-90, cols lon -180..178.\n` +
    `export const GEOID_ROWS = ${rows};\nexport const GEOID_COLS = ${cols};\nexport const GEOID_B64 = '${b64}';\n`;
  fs.writeFileSync(path.join(ROOT, 'src', 'lib', 'geoidGrid.ts'), ts);
  console.log('geoid grid ok', b64.length, 'chars');
}

// ---------- CPU moon renderer (orthographic, near side) ----------
function srgbToLin(c) { c /= 255; return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); }
function linToSrgb(c) { c = Math.max(0, c); const v = c <= 0.0031308 ? c * 12.92 : 1.055 * Math.pow(c, 1 / 2.4) - 0.055; return Math.min(255, Math.round(v * 255)); }

async function loadRgb(file, w, h) {
  const { data } = await sharp(file, big).resize(w, h).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  return data;
}

function sample(buf, w, h, u, v, ch) {
  // bilinear, u wraps, v clamps
  const x = u * w - 0.5, y = v * h - 0.5;
  const x0 = Math.floor(x), y0 = Math.floor(y);
  const fx = x - x0, fy = y - y0;
  const res = [0, 0, 0];
  for (let k = 0; k < ch; k++) {
    const g = (xx, yy) => buf[(Math.min(Math.max(yy, 0), h - 1) * w + ((xx % w) + w) % w) * ch + k];
    res[k] = (g(x0, y0) * (1 - fx) + g(x0 + 1, y0) * fx) * (1 - fy) + (g(x0, y0 + 1) * (1 - fx) + g(x0 + 1, y0 + 1) * fx) * fy;
  }
  return res;
}

let TEX = null;
async function moonTex() {
  if (!TEX) {
    TEX = {
      color: await loadRgb(out('textures', 'moon-color-4k.jpg'), 4096, 2048),
      normal: await loadRgb(out('textures', 'moon-normal-2k.jpg'), 2048, 1024),
    };
  }
  return TEX;
}

// phaseAngleDeg: 0 = full, 90 = quarter. waxing => lit on the right. rot: image rotation (rad)
async function renderMoonDisk(size, { phaseAngleDeg = 40, waxing = true, exposure = 1.25, earthshine = 0.035, rotate = 0 } = {}) {
  const { color, normal } = await moonTex();
  const ss = 2;
  const S = size * ss;
  const px = Buffer.alloc(S * S * 4);
  const a = (phaseAngleDeg * Math.PI) / 180;
  const sun = [Math.cos(a), (waxing ? 1 : -1) * Math.sin(a), 0];
  const L = Math.max(0, 1 - phaseAngleDeg / 140);
  const cr = Math.cos(rotate), sr = Math.sin(rotate);
  for (let j = 0; j < S; j++) {
    for (let i = 0; i < S; i++) {
      let X = ((i + 0.5) / S) * 2 - 1;
      let Y = 1 - ((j + 0.5) / S) * 2;
      const r2 = X * X + Y * Y;
      const o = (j * S + i) * 4;
      if (r2 > 1) { px[o + 3] = 0; continue; }
      const Xr = X * cr + Y * sr, Yr = -X * sr + Y * cr;
      const nX = Math.sqrt(Math.max(0, 1 - Xr * Xr - Yr * Yr));
      const n = [nX, Xr, Yr];
      const lon = Math.atan2(n[1], n[0]);
      const lat = Math.asin(Math.max(-1, Math.min(1, n[2])));
      const u = lon / (2 * Math.PI) + 0.5;
      const v = 0.5 - lat / Math.PI;
      const c = sample(color, 4096, 2048, u, v, 3);
      const nm = sample(normal, 2048, 1024, u, v, 3).map((q) => (q / 255) * 2 - 1);
      const east = [-Math.sin(lon), Math.cos(lon), 0];
      const north = [-Math.sin(lat) * Math.cos(lon), -Math.sin(lat) * Math.sin(lon), Math.cos(lat)];
      const np = [0, 1, 2].map((k) => east[k] * nm[0] * 1.6 + north[k] * nm[1] * 1.6 + n[k] * nm[2]);
      const nl = Math.hypot(...np);
      const mu0p = (np[0] * sun[0] + np[1] * sun[1] + np[2] * sun[2]) / nl;
      const mu0g = n[0] * sun[0] + n[1] * sun[1] + n[2] * sun[2];
      const mu = n[0];
      const term = Math.min(1, Math.max(0, (mu0g + 0.015) / 0.05));
      const m0 = Math.max(mu0p, 0);
      const lit = (2 * L * m0) / (m0 + mu + 1e-4) + (1 - L) * m0;
      const shade = lit * term * 0.62 + earthshine * mu;
      const alpha = Math.min(1, Math.max(0, (1 - Math.sqrt(r2)) * S * 0.5));
      px[o] = linToSrgb(srgbToLin(c[0]) * shade * exposure * 1.0);
      px[o + 1] = linToSrgb(srgbToLin(c[1]) * shade * exposure * 1.0);
      px[o + 2] = linToSrgb(srgbToLin(c[2]) * shade * exposure * 1.04);
      px[o + 3] = Math.round(alpha * 255);
    }
  }
  return sharp(px, { raw: { width: S, height: S, channels: 4 } }).resize(size, size, { kernel: 'lanczos3' }).png().toBuffer();
}

// Generic twin-jet planform, nose up, 100x100 box
const PLANE_PATH =
  'M50 2.5c2.3 0 3.6 3.2 3.9 8.6l.2 28.4 17.6 9.7v-3.3l3.6-.1v5.4l19.2 10.6v5.2L54.3 54.8 53.9 80l11.6 9.4v4.3l-13.4-3.1-.9 6.4h-2.4l-.9-6.4-13.4 3.1v-4.3L46.1 80l-.4-25.2-40.2 12.2v-5.2l19.2-10.6v-5.4l3.6.1v3.3l17.6-9.7.2-28.4c.3-5.4 1.6-8.6 3.9-8.6z';

function iconSvg(size, moonPng, { bgPad = 0, moonScale = 0.78, plane = true, rounded = false } = {}) {
  const m = Math.round(size * moonScale);
  const off = Math.round((size - m) / 2);
  const b64 = moonPng.toString('base64');
  const ps = size * 0.27;
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <defs>
    <radialGradient id="bg" cx="50%" cy="42%" r="75%">
      <stop offset="0" stop-color="#121a2c"/>
      <stop offset="0.55" stop-color="#070b14"/>
      <stop offset="1" stop-color="#020306"/>
    </radialGradient>
    <radialGradient id="glow" cx="50%" cy="50%" r="50%">
      <stop offset="0.62" stop-color="#f4ead2" stop-opacity="0.20"/>
      <stop offset="0.80" stop-color="#f4ead2" stop-opacity="0.05"/>
      <stop offset="1" stop-color="#f4ead2" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="${size}" height="${size}" ${rounded ? `rx="${size * 0.22}"` : ''} fill="url(#bg)"/>
  <circle cx="${size / 2}" cy="${size / 2}" r="${m * 0.66}" fill="url(#glow)"/>
  <image x="${off + bgPad}" y="${off + bgPad}" width="${m - 2 * bgPad}" height="${m - 2 * bgPad}" xlink:href="data:image/png;base64,${b64}"/>
  ${plane ? `<g transform="translate(${size * 0.585} ${size * 0.4}) rotate(-62) translate(${-ps / 2} ${-ps / 2}) scale(${ps / 100})"><path d="${PLANE_PATH}" fill="#04060a"/></g>` : ''}
</svg>`);
}

async function icons() {
  const moon = await renderMoonDisk(1024, { phaseAngleDeg: 38, waxing: true, rotate: 0.32 });
  const renderIcon = async (size, file, opts = {}) => {
    const svg = iconSvg(1024, moon, opts);
    await sharp(svg).resize(size, size).png({ compressionLevel: 9 }).toFile(file);
  };
  await renderIcon(512, out('icons', 'icon-512.png'));
  await renderIcon(192, out('icons', 'icon-192.png'));
  await renderIcon(180, out('icons', 'apple-touch-icon.png'));
  await renderIcon(64, out('icons', 'favicon-64.png'));
  await renderIcon(32, out('icons', 'favicon-32.png'));
  await renderIcon(512, out('icons', 'maskable-512.png'), { moonScale: 0.6 });
  fs.mkdirSync(path.join(ROOT, 'build'), { recursive: true });
  await sharp(iconSvg(1024, moon, { rounded: true })).resize(512, 512).png().toFile(path.join(ROOT, 'build', 'icon.png'));
  console.log('icons ok');
  return moon;
}

const SPLASH = [
  [440, 956, 3], [402, 874, 3], [420, 912, 3], [430, 932, 3], [393, 852, 3], [390, 844, 3],
  [428, 926, 3], [375, 812, 3], [414, 896, 3], [414, 896, 2], [375, 667, 2], [414, 736, 3], [320, 568, 2],
];

async function splash(moon) {
  const list = [];
  for (const [w, h, d] of SPLASH) {
    const W = w * d, H = h * d;
    const m = Math.round(W * 0.42);
    const moonBuf = await sharp(moon).resize(m, m).png().toBuffer();
    const glow = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}"><defs>
      <radialGradient id="g" cx="50%" cy="46%" r="60%"><stop offset="0" stop-color="#0f1626"/><stop offset="0.6" stop-color="#05070d"/><stop offset="1" stop-color="#030409"/></radialGradient>
      <radialGradient id="h" cx="50%" cy="50%" r="50%"><stop offset="0.6" stop-color="#f4ead2" stop-opacity="0.14"/><stop offset="1" stop-color="#f4ead2" stop-opacity="0"/></radialGradient></defs>
      <rect width="100%" height="100%" fill="url(#g)"/><circle cx="${W / 2}" cy="${H * 0.46}" r="${m * 0.75}" fill="url(#h)"/></svg>`);
    const file = `splash-${W}x${H}.png`;
    await sharp(glow)
      .composite([{ input: moonBuf, left: Math.round((W - m) / 2), top: Math.round(H * 0.46 - m / 2) }])
      .png({ compressionLevel: 9, palette: false })
      .toFile(out('splash', file));
    list.push({ w, h, d, file });
  }
  fs.writeFileSync(path.join(ROOT, 'scripts', 'splash-list.json'), JSON.stringify(list, null, 1));
  console.log('splash ok');
}

